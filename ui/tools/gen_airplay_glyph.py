"""Generates ui/font_airplay_glyph.c: one glyph, the AirPlay mark (a screen with a triangle rising into its open
bottom edge), at every size the theme font roles use, as LVGL 4 bpp fonts. LVGL's symbol set has no AirPlay icon
(Working mode used the Wi-Fi fan). It is drawn here from geometry, so no third-party artwork is involved.

The glyph sits at U+E800 (private use; DISKOS_SYMBOL_AIRPLAY in theme.h). theme.c puts the matching size right
behind every role's face in its fallback chain, so any label in any theme can show it.

Needs Pillow:  python3 ui/tools/gen_airplay_glyph.py"""
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "font_airplay_glyph.c"
CODEPOINT = 0xE800
SIZES = list(range(8, 49)) + [56, 64, 72, 80]
SS = 16                                  # supersampling

def render(px):
    # Box like Montserrat's symbols: about 1.15 em wide, 0.95 em tall, slightly below the baseline.
    w, h = max(4, round(px * 1.12)), max(4, round(px * 0.94))
    W, H = w * SS, h * SS
    im = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(im)
    stroke = max(SS, round(px * 0.11 * SS))
    rad = round(px * 0.16 * SS)
    screen_b = round(H * 0.74)           # the screen's bottom edge
    d.rounded_rectangle([0, 0, W - 1, screen_b], radius=rad, fill=255)
    d.rounded_rectangle([stroke, stroke, W - 1 - stroke, screen_b - stroke], radius=max(0, rad - stroke), fill=0)
    gap = round(W * 0.50)                # the opening the triangle rises into
    d.rectangle([(W - gap) // 2, screen_b - stroke - 1, (W + gap) // 2, screen_b + 1], fill=0)
    tri_w = round(W * 0.62)
    top = round(H * 0.44)
    d.polygon([(W / 2, top), ((W - tri_w) / 2, H - 1), ((W + tri_w) / 2, H - 1)], fill=255)
    im = im.resize((w, h), Image.LANCZOS)
    return w, h, im

def nibbles(im, w, h):
    px = list(im.get_flattened_data() if hasattr(im, "get_flattened_data") else im.getdata())
    vals = [min(15, (v + 8) // 17) for v in px]
    if len(vals) % 2:
        vals.append(0)
    return [(vals[i] << 4) | vals[i + 1] for i in range(0, len(vals), 2)]

def main():
    parts = ["/* SPDX-License-Identifier: GPL-3.0-or-later */",
             "/* GENERATED by tools/gen_airplay_glyph.py - do not edit. The AirPlay mark at U+E800 (DISKOS_SYMBOL_AIRPLAY),",
             " * one LVGL 4 bpp font per size; theme.c chains the matching one behind every theme font. */",
             '#include "lvgl/lvgl.h"', ""]
    names = []
    for px in SIZES:
        w, h, im = render(px)
        data = nibbles(im, w, h)
        ofs_y = -max(0, round(px * 0.07))
        name = f"font_airplay_{px}"
        names.append((px, name))
        rows = ", ".join(f"0x{b:02x}" for b in data)
        line_height = max(h, px)
        base_line = max(0, round(px * 0.18))
        parts += [
            f"static const uint8_t {name}_bm[] = {{ {rows} }};",
            f"static const lv_font_fmt_txt_glyph_dsc_t {name}_gd[] = {{ {{0}},"
            f" {{.bitmap_index = 0, .adv_w = {(w + max(1, px // 8)) * 16}, .box_w = {w}, .box_h = {h}, .ofs_x = 0, .ofs_y = {ofs_y}}} }};",
            f"static const lv_font_fmt_txt_cmap_t {name}_cm[] = {{ {{ .range_start = {CODEPOINT}, .range_length = 1, .glyph_id_start = 1,"
            f" .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY }} }};",
            f"static const lv_font_fmt_txt_dsc_t {name}_dsc = {{ .glyph_bitmap = {name}_bm, .glyph_dsc = {name}_gd, .cmaps = {name}_cm,"
            f" .kern_dsc = NULL, .kern_scale = 0, .cmap_num = 1, .bpp = 4, .kern_classes = 0, .bitmap_format = 0 }};",
            f"static const lv_font_t {name} = {{ .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt, .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,"
            f" .line_height = {line_height}, .base_line = {base_line}, .subpx = LV_FONT_SUBPX_NONE, .underline_position = 0,"
            f" .underline_thickness = 0, .dsc = &{name}_dsc, .fallback = NULL, .user_data = NULL }};",
            ""]
    parts.append("/* the glyph font nearest to `px` */")
    parts.append("const lv_font_t *airplay_glyph_font(int px){")
    parts.append("    static const struct { int px; const lv_font_t *f; } T[] = { " + ", ".join(f"{{ {p}, &{n} }}" for p, n in names) + " };")
    parts.append("    int best = 0; for(unsigned i = 1; i < sizeof T / sizeof T[0]; i++) if(abs(T[i].px - px) < abs(T[best].px - px)) best = (int)i;")
    parts.append("    return T[best].f;")
    parts.append("}")
    text = "\n".join(parts) + "\n"
    text = text.replace('#include "lvgl/lvgl.h"', '#include "lvgl/lvgl.h"\n#include <stdlib.h>')
    OUT.write_text(text)
    # a preview sheet for review (not part of the build)
    sheet = Image.new("L", (sum(render(p)[0] + 4 for p in (16, 20, 24, 28, 36, 48, 80)), 84), 0)
    x = 0
    for p in (16, 20, 24, 28, 36, 48, 80):
        w, h, im = render(p); sheet.paste(im, (x, 0)); x += w + 4
    sheet.save(ROOT / "tests" / "host_build" / "airplay_glyph_preview.png") if (ROOT / "tests" / "host_build").is_dir() else None
    print(f"wrote {OUT.name}: {len(SIZES)} sizes")

if __name__ == "__main__":
    main()
