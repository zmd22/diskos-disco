#!/usr/bin/env python3
"""Generate img_classic_logo.c (rb_classic boot logo, A8 alpha) from images/classic/rb_logo.png."""
from pathlib import Path
from PIL import Image

UI = Path(__file__).resolve().parent.parent
SIZE = 124

def main():
    a = Image.open(UI / 'images/classic/rb_logo.png').convert('L').resize((SIZE, SIZE), Image.LANCZOS)
    px = a.tobytes()
    rows = [', '.join(f'0x{b:02x}' for b in px[i:i + 24]) for i in range(0, len(px), 24)]
    body = ',\n    '.join(rows)
    out = f'''/* SPDX-License-Identifier: GPL-3.0-or-later */
/* rb_classic boot logo: {SIZE}x{SIZE} A8 coverage, drawn in the theme's ink. Generated by tools/gen_classic_logo.py. */
#include "lvgl/lvgl.h"
static const uint8_t px[{SIZE * SIZE}] = {{
    {body}
}};
const lv_image_dsc_t img_classic_logo = {{
    .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .w = {SIZE}, .h = {SIZE}, .stride = {SIZE} }},
    .data_size = sizeof px, .data = px,
}};
'''
    (UI / 'img_classic_logo.c').write_text(out)

if __name__ == '__main__':
    main()
