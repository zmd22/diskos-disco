#!/usr/bin/env python3
"""Generate img_classic_logo.c (Graphite boot mark and wordmark, A8 alpha). The GR mark is drawn here;
the wordmark is set in Open Sans Condensed Bold (OFL, licenses/OpenSans-OFL.txt)."""
import argparse
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

UI = Path(__file__).resolve().parent.parent
SS = 4                     # supersampling
MARK_SCALE = 1.1           # 1.0 = 160x105 grid units
WORD, WORD_PX, WORD_TRACK = "GRAPHITE", 46, 4


def mark():
    """GR ligature: the G's right stroke rises into the R stem, its bar runs into the R bowl."""
    k = SS * MARK_SCALE
    w, h = round(160 * MARK_SCALE), round(105 * MARK_SCALE)
    im = Image.new("L", (w * SS, h * SS), 0)
    d = ImageDraw.Draw(im)
    P = lambda x, y: (x * k, y * k)
    d.pieslice([P(0, 1), P(104, 105)], 0, 292, fill=255)             # G ring
    d.ellipse([P(16, 17), P(88, 89)], fill=0)
    d.rectangle([P(88, 0), P(104, 53)], fill=255)                   # shared stem
    d.rectangle([P(88, 0), P(118, 15)], fill=255)                   # bowl top
    d.pieslice([P(84, 0), P(152, 67)], 270, 90, fill=255)           # bowl round
    d.rectangle([P(56, 52), P(118, 67)], fill=255)                  # G bar = bowl bottom
    d.rectangle([P(104, 15), P(118, 52)], fill=0)                   # counter
    d.pieslice([P(100, 15), P(136, 52)], 270, 90, fill=0)
    d.polygon([P(112, 60), P(131, 60), P(160, 105), P(141, 105)], fill=255)   # leg
    return im.resize((w, h), Image.LANCZOS)


def word(font_path):
    fo = ImageFont.truetype(font_path, WORD_PX * SS)
    im = Image.new("L", (WORD_PX * SS * len(WORD), WORD_PX * SS * 2), 0)
    d = ImageDraw.Draw(im)
    x = 0
    for ch in WORD:
        d.text((x, 0), ch, font=fo, fill=255)
        x += d.textlength(ch, font=fo) + WORD_TRACK * SS
    l, t, r, b = im.getbbox()
    pad = lambda v: (v + SS - 1) // SS * SS
    im = im.crop((l // SS * SS, t // SS * SS, pad(r), pad(b)))
    return im.resize((im.width // SS, im.height // SS), Image.LANCZOS)


def emit(name, im):
    px = im.tobytes()
    rows = [', '.join(f'0x{b:02x}' for b in px[i:i + 24]) for i in range(0, len(px), 24)]
    body = ',\n    '.join(rows)
    return f'''static const uint8_t {name}_px[{len(px)}] = {{
    {body}
}};
const lv_image_dsc_t {name} = {{
    .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .w = {im.width}, .h = {im.height}, .stride = {im.width} }},
    .data_size = sizeof {name}_px, .data = {name}_px,
}};
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--font", default="/usr/share/fonts/TTF/OpenSans-CondensedBold.ttf")
    a = ap.parse_args()
    m, w = mark(), word(a.font)
    out = ('/* SPDX-License-Identifier: GPL-3.0-or-later */\n'
           f'/* Graphite boot logo: the GR mark ({m.width}x{m.height}) and the wordmark ({w.width}x{w.height}), A8 coverage drawn\n'
           ' * in the theme\'s ink. Generated by tools/gen_classic_logo.py. */\n'
           '#include "lvgl/lvgl.h"\n' + emit("img_classic_mark", m) + emit("img_classic_word", w))
    (UI / 'img_classic_logo.c').write_text(out)
    print(f"mark {m.width}x{m.height}, word {w.width}x{w.height}")


if __name__ == '__main__':
    main()
